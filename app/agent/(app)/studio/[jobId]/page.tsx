import Link from "next/link";
import { notFound } from "next/navigation";
import { Act, CvEditor, EmphasisForm } from "@/components/agent/client";
import { CvPane } from "@/components/agent/CvPane";
import { Chip, Notice, Page, Score, Tabs } from "@/components/agent/ui";
import { buildBaselineCv } from "@/lib/agent/cv/build";
import { getCtx } from "@/lib/agent/runtime";

const TABS = [
  { key: "compare", label: "Compare" },
  { key: "pdf", label: "PDF preview" },
  { key: "claims", label: "Claims & evidence" },
  { key: "ats", label: "ATS checks" },
  { key: "edit", label: "Edit" },
];

export default async function StudioJob({ params, searchParams }: { params: Promise<{ jobId: string }>; searchParams: Promise<{ v?: string; tab?: string }> }) {
  const { jobId } = await params;
  const { v, tab = "compare" } = await searchParams;
  const ctx = await getCtx();
  const [job, match, profile, all, letters, apps] = await Promise.all([ctx.store.get("jobs", jobId), ctx.store.get("matches", `m_${jobId}`), ctx.store.get("profile", "profile"), ctx.store.list("cvVersions"), ctx.store.list("coverLetters"), ctx.store.list("applications")]);
  if (!job || !profile) notFound();
  const versions = all.filter((x) => x.jobId === jobId).sort((a, b) => b.version - a.version);
  const cv = versions.find((x) => x.id === v) ?? versions[0];
  const base = `/agent/studio/${jobId}`;
  const q = (t: string) => `${base}?tab=${t}${cv ? `&v=${cv.id}` : ""}`;
  const app = apps.find((a) => a.jobId === jobId);
  const letter = letters.filter((l) => l.jobId === jobId).sort((a, b) => b.createdAt.localeCompare(a.createdAt))[0];

  if (!cv) {
    return (
      <Page title={job.title} sub={job.employer}>
        <Notice tone="info">No CV exists for this job yet.</Notice>
        <div style={{ marginTop: 12 }}>{match && match.eligibility !== "INELIGIBLE" ? <Act variant="primary" url="/api/agent/cv" body={{ action: "prepare", jobId }} goto={`/agent/studio/${jobId}`}>Prepare tailored CV</Act> : <Notice tone="warn">This job failed eligibility, so no CV is generated.</Notice>}</div>
      </Page>
    );
  }

  const baseline = buildBaselineCv(profile);
  const original = profile.originalCvDocId ? await ctx.store.get("documents", profile.originalCvDocId) : null;
  const gaps = match?.gaps.map((g) => g.requirement) ?? [];
  const suggestions = [...new Set([...(match?.matched.filter((m) => m.strength !== "LISTED_ONLY").map((m) => m.requirement) ?? []), ...(job.preferredSkills.filter((s) => !gaps.includes(s)))])].slice(0, 12);
  const newerExists = versions[0].id !== cv.id;

  return (
    <Page
      title={job.title}
      sub={<>{job.employer} · tailored CV v{cv.version} <Chip tone={cv.status === "APPROVED" ? "ok" : cv.status === "DRAFT" ? "warn" : ""}>{cv.status.toLowerCase()}</Chip> <span className="t-sub">· generated by {cv.generator}</span></>}
      actions={
        <>
          <Link className="btn" href={`/agent/jobs/${jobId}`}>Job details</Link>
          {cv.pdfDocId ? <a className="btn" href={`/api/agent/documents/${cv.pdfDocId}`}>Download PDF</a> : null}
          {cv.docxDocId ? <a className="btn" href={`/api/agent/documents/${cv.docxDocId}`}>Download DOCX</a> : null}
        </>
      }
    >
      <div className="grid g3" style={{ marginBottom: 16, alignItems: "start" }}>
        <div className="card">
          <h3 style={{ marginBottom: 8 }}>Job-specific match</h3>
          <div style={{ display: "flex", alignItems: "center", gap: 10 }}><Score value={cv.matchScore} /><span className="t-sub">{match?.recommendation.toLowerCase()} · {match?.eligibility.toLowerCase()}</span></div>
        </div>
        <div className="card">
          <h3 style={{ marginBottom: 8 }}>Claims validation</h3>
          {cv.validation.pass ? <Chip tone="ok">All {cv.validation.claims.length} claims trace to verified facts</Chip> : <Chip tone="bad">{cv.validation.violations.length} unsupported claim(s): cannot be approved</Chip>}
        </div>
        <div className="card">
          <h3 style={{ marginBottom: 8 }}>Versions</h3>
          <div className="btns">
            {versions.map((x) => <Link key={x.id} className="btn sm" style={x.id === cv.id ? { background: "var(--accent-soft)", color: "var(--accent)" } : {}} href={`${base}?tab=${tab}&v=${x.id}`}>v{x.version} · {x.status.toLowerCase()}</Link>)}
          </div>
        </div>
      </div>

      {newerExists ? <div style={{ marginBottom: 12 }}><Notice tone="info">You are viewing an older version. Newer: v{versions[0].version}.</Notice></div> : null}
      <div className="card" style={{ marginBottom: 16 }}>
        <div className="card-head"><h2>Review</h2></div>
        <div className="btns">
          <Act variant="primary" url="/api/agent/cv" body={{ action: "review", id: cv.id, decision: "APPROVED" }} disabled={!cv.validation.pass || cv.status === "APPROVED" || cv.status === "SUPERSEDED"}>Approve this version</Act>
          <Act variant="danger" url="/api/agent/cv" body={{ action: "review", id: cv.id, decision: "REJECTED" }} disabled={cv.status === "REJECTED" || cv.status === "SUPERSEDED"}>Reject</Act>
          {app && cv.status === "APPROVED" ? <Link className="btn" href={`/agent/applications/${app.id}`}>Go to application →</Link> : null}
        </div>
        {cv.status === "APPROVED" ? <p className="hint" style={{ marginBottom: 0 }}>Approved versions are frozen. To change anything, edit or regenerate: that creates a new version and leaves this one untouched until you approve the replacement.</p> : null}
      </div>

      <Tabs current={tab} items={TABS.map((t) => ({ ...t, href: q(t.key) }))} />

      {tab === "compare" ? (
        <div className="stack">
          <div className="card">
            <h2 style={{ marginBottom: 8 }}>What changed for this job</h2>
            <ul style={{ margin: 0, paddingLeft: 18 }}>{cv.changeSummary.map((c, i) => <li key={i}>{c}</li>)}</ul>
          </div>
          {cv.questions.length ? (
            <div className="card">
              <h2 style={{ marginBottom: 8 }}>Questions for you</h2>
              <p className="hint" style={{ marginTop: 0 }}>These claims could not be made without evidence. Nothing was invented to fill them.</p>
              <ul style={{ margin: 0, paddingLeft: 18 }}>{cv.questions.map((c, i) => <li key={i}>{c}</li>)}</ul>
              <p style={{ marginBottom: 0 }}><Link href="/agent/settings?tab=profile">Add or verify facts →</Link></p>
            </div>
          ) : null}
          <div className="split">
            <div><h3 style={{ marginBottom: 6 }}>Your original CV (master) {original ? <a className="btn sm" style={{ marginLeft: 8 }} href={`/api/agent/documents/${original.id}`}>Download original</a> : null}</h3><CvPane doc={baseline} other={cv.doc} kind="orig" /></div>
            <div><h3 style={{ marginBottom: 6 }}>Tailored v{cv.version}</h3><CvPane doc={cv.doc} other={baseline} kind="tail" /></div>
          </div>
          <div className="hint">Struck-through lines were left out for this role; highlighted lines were reworded. Both are checked against your verified facts.</div>
        </div>
      ) : null}

      {tab === "pdf" ? (cv.pdfDocId ? <iframe className="pdf" title="Tailored CV PDF preview" src={`/api/agent/documents/${cv.pdfDocId}?inline=1`} /> : <Notice tone="warn">No PDF stored.</Notice>) : null}

      {tab === "claims" ? (
        <div className="stack">
          {cv.validation.violations.length ? <Notice tone="bad"><b>Unsupported:</b><ul style={{ margin: "6px 0 0", paddingLeft: 18 }}>{cv.validation.violations.map((x, i) => <li key={i}>{x}</li>)}</ul></Notice> : <Notice tone="ok">Every claim in this CV traces to a verified fact.</Notice>}
          <div className="tablewrap">
            <table>
              <thead><tr><th>Where</th><th>Text</th><th>Status</th><th>Evidence</th></tr></thead>
              <tbody>
                {cv.validation.claims.filter((c) => !c.location.startsWith("Skills")).map((c, i) => (
                  <tr key={i}>
                    <td className="t-sub" style={{ minWidth: 160 }}>{c.location}</td>
                    <td style={{ minWidth: 280 }}>{c.text}</td>
                    <td><Chip tone={c.status === "VERIFIED" ? "ok" : "bad"}>{c.status === "VERIFIED" ? "Verified" : "Unsupported"}</Chip>{c.problem ? <div className="t-sub">{c.problem}</div> : null}</td>
                    <td className="mono">{c.factIds.map((f) => profile.facts.find((x) => x.id === f)?.source.ref ?? f).join("; ")}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="hint">Skills listed: {cv.validation.claims.filter((c) => c.location.startsWith("Skills")).length}, all matched to your verified skill list.</div>
        </div>
      ) : null}

      {tab === "ats" ? (
        <div className="tablewrap">
          <table>
            <thead><tr><th>Check</th><th>Result</th><th>Detail</th></tr></thead>
            <tbody>{cv.ats.map((a) => <tr key={a.id}><td className="t-title">{a.label}</td><td><Chip tone={a.status === "PASS" ? "ok" : a.status === "WARN" ? "warn" : "bad"}>{a.status.toLowerCase()}</Chip></td><td>{a.detail}</td></tr>)}</tbody>
          </table>
        </div>
      ) : null}

      {tab === "edit" ? (
        <div className="grid g2" style={{ alignItems: "start" }}>
          <div className="card"><h2 style={{ marginBottom: 10 }}>Edit text</h2><CvEditor jobId={jobId} parentId={cv.id} doc={cv.doc} /></div>
          <div className="stack">
            <div className="card"><h2 style={{ marginBottom: 10 }}>Regenerate with different emphasis</h2><EmphasisForm jobId={jobId} parentId={cv.id} suggestions={suggestions} /></div>
            {letter ? (
              <div className="card">
                <div className="card-head"><h2>Cover letter</h2><div className="btns">{letter.pdfDocId ? <a className="btn sm" href={`/api/agent/documents/${letter.pdfDocId}`}>PDF</a> : null}{letter.docxDocId ? <a className="btn sm" href={`/api/agent/documents/${letter.docxDocId}`}>DOCX</a> : null}</div></div>
                <div className="jd" style={{ maxHeight: 260 }}>{letter.text}</div>
              </div>
            ) : null}
          </div>
        </div>
      ) : null}
    </Page>
  );
}
